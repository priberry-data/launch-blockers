// Writes simulator/patterns.js from data/patterns.json, so the simulator opens from a file:// URL with no fetch.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const { patterns, version } = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "patterns.json"), "utf8"));
const out = {};
patterns.forEach((p, i) => {
  const inc = p.incidents[0];
  out[p.id] = {
    n: i + 1,
    title: p.title,
    severity: p.severity,
    why: p.why,
    fix: p.fix_prompt,
    anchor: `https://github.com/priberry-data/launch-blockers/blob/main/PLAYBOOK.md#${i + 1}-${p.id}`,
    source: inc ? { date: inc.date, title: inc.title, what: inc.what, name: inc.source_name, url: inc.source_url } : { date: null, title: p.rules[0].source_name, what: null, name: p.rules[0].source_name, url: p.rules[0].source_url },
  };
});
fs.writeFileSync(path.join(ROOT, "simulator", "patterns.js"), `// Generated by scripts/sim-data.mjs from data/patterns.json (${version}). Don't edit by hand.\nwindow.PATTERNS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`simulator/patterns.js: ${patterns.length} patterns`);
